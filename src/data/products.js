export function checkFitment(product, vehicle) {
  if (!vehicle || !vehicle.make) return { status: 'universal', label: 'UNIVERSAL FIT' }
  const makes = product.compatibleMakes || []
  if (!makes.includes(vehicle.make)) {
    return {
      status: 'incompatible',
      label: 'DOES NOT FIT',
      reason: `Engineered strictly for ${makes.join(', ')} chassis architectures.`
    }
  }
  const models = product.compatibleModels?.[vehicle.make] || []
  if (models.includes(vehicle.model)) {
    return {
      status: 'exact',
      label: 'EXACT FIT GUARANTEED',
      reason: `Calibrated for ${vehicle.year} ${vehicle.make} ${vehicle.model} (${vehicle.engine || 'Direct OE'})`
    }
  }
  return {
    status: 'warning',
    label: 'VERIFY ENGINE TRIM',
    reason: `Fits some ${vehicle.make} configurations; verify sub-trim or VIN.`
  }
}
